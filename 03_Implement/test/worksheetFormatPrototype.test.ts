import test from 'node:test';
import assert from 'node:assert/strict';
import {
  createWorksheetFormatPrototype,
  matchWorksheetFormatSnapshot,
  SHEETJS_CE_XLSX_0203_SOURCE_PROFILE,
  WORKSHEET_FORMAT_FEATURE_VERSION,
  type WorksheetFormatPrototype,
} from '../src/experimental/worksheetFormatPrototype.js';
import type { WorksheetFormatSnapshot } from '../src/experimental/worksheetFormatFeatureAdapter.js';

function releaseSnapshot(fillTone: 'dark' | 'gray' = 'dark'): WorksheetFormatSnapshot {
  return {
    cells: [
      { row: 0, column: 0, text: 'リリース判定表' },
      { row: 1, column: 0, text: 'ID', fillTone, borderKind: 'grid' },
      { row: 1, column: 1, text: '項目', fillTone, borderKind: 'grid' },
      { row: 1, column: 2, text: '判定', fillTone, borderKind: 'grid' },
      { row: 1, column: 3, text: '確認者', fillTone, borderKind: 'grid' },
      { row: 1, column: 4, text: '備考', fillTone, borderKind: 'grid' },
      { row: 1, column: 5, text: '期限', fillTone, borderKind: 'grid' },
      { row: 2, column: 0, text: 'R-001', borderKind: 'grid' },
      { row: 2, column: 1, text: '疎通確認', borderKind: 'grid' },
      { row: 2, column: 2, text: 'OK', borderKind: 'grid' },
      { row: 2, column: 3, text: '佐藤', borderKind: 'grid' },
      { row: 2, column: 5, text: '2026-09-30', borderKind: 'grid' },
    ],
    merges: [{ startRow: 0, startColumn: 0, endRow: 0, endColumn: 5 }],
  };
}

test('creates a versioned SheetJS prototype from the full adapter observation but excludes unguaranteed border evidence', () => {
  const prototype = createWorksheetFormatPrototype(
    'release-checklist',
    releaseSnapshot(),
    SHEETJS_CE_XLSX_0203_SOURCE_PROFILE,
  );

  assert.equal(prototype.featureVersion, WORKSHEET_FORMAT_FEATURE_VERSION);
  assert.equal(prototype.sourceProfileId, SHEETJS_CE_XLSX_0203_SOURCE_PROFILE.id);
  assert.deepEqual(prototype.sourceEvidence, ['fill', 'structure']);
  assert.ok(prototype.features.includes('header:dark-fill'));
  assert.ok(prototype.features.includes('column:判定'));
  assert.ok(!prototype.features.includes('border:grid'));
});

test('a full-style source profile can retain border evidence explicitly', () => {
  const prototype = createWorksheetFormatPrototype('release-checklist', releaseSnapshot(), {
    id: 'synthetic-full-style-v1',
    evidence: ['structure', 'fill', 'border'],
  });

  assert.ok(prototype.features.includes('border:grid'));
});

test('matches a fill drift against a prototype generated by the same adapter and source profile', () => {
  const prototype = createWorksheetFormatPrototype(
    'release-checklist',
    releaseSnapshot('dark'),
    SHEETJS_CE_XLSX_0203_SOURCE_PROFILE,
  );
  const result = matchWorksheetFormatSnapshot(
    releaseSnapshot('gray'),
    [prototype],
    SHEETJS_CE_XLSX_0203_SOURCE_PROFILE,
  );

  assert.equal(result.match.status, 'matched');
  assert.equal(result.match.winner?.prototypeId, 'release-checklist');
  assert.ok((result.match.winner?.deviationScore ?? 0) > 0);
  assert.ok(result.observation.features.includes('border:grid'));
  assert.ok(!result.comparedFeatures.includes('border:grid'));
});

test('rejects a prototype from a different source profile or evidence contract', () => {
  const fullStylePrototype = createWorksheetFormatPrototype('release-checklist', releaseSnapshot(), {
    id: 'synthetic-full-style-v1',
    evidence: ['structure', 'fill', 'border'],
  });
  assert.throws(
    () => matchWorksheetFormatSnapshot(releaseSnapshot(), [fullStylePrototype], SHEETJS_CE_XLSX_0203_SOURCE_PROFILE),
    /Incompatible worksheet format source profile/,
  );

  const incompatibleEvidence: WorksheetFormatPrototype = {
    ...createWorksheetFormatPrototype('release-checklist', releaseSnapshot(), SHEETJS_CE_XLSX_0203_SOURCE_PROFILE),
    sourceEvidence: ['structure'],
  };
  assert.throws(
    () => matchWorksheetFormatSnapshot(releaseSnapshot(), [incompatibleEvidence], SHEETJS_CE_XLSX_0203_SOURCE_PROFILE),
    /Incompatible worksheet format source profile/,
  );
});

test('rejects incompatible feature versions before matching', () => {
  const prototype = createWorksheetFormatPrototype(
    'release-checklist',
    releaseSnapshot(),
    SHEETJS_CE_XLSX_0203_SOURCE_PROFILE,
  );
  (prototype as { featureVersion: string }).featureVersion = 'worksheet-format-v0';

  assert.throws(
    () => matchWorksheetFormatSnapshot(releaseSnapshot(), [prototype], SHEETJS_CE_XLSX_0203_SOURCE_PROFILE),
    /Incompatible worksheet format feature version/,
  );
});

test('refuses empty profile metadata and a baseline without observable table features', () => {
  assert.throws(
    () => createWorksheetFormatPrototype('x', releaseSnapshot(), { id: '   ', evidence: ['structure'] }),
    /profile id/,
  );
  assert.throws(
    () => createWorksheetFormatPrototype('x', releaseSnapshot(), { id: 'profile', evidence: [] }),
    /at least one evidence/,
  );
  assert.throws(
    () => createWorksheetFormatPrototype('x', { cells: [{ row: 0, column: 0, text: '自由記述' }] }, { id: 'profile', evidence: ['structure'] }),
    /no observable format features/,
  );
});
